// Copies the business-rule modules the frontend and the API must agree on into
// src/shared/. Run by the Dockerfile at build time and by `npm run shared` locally.
//
// Copying (rather than re-implementing) keeps one definition of the email templates,
// the overtime rules and the demo data: assets/js is the original, src/shared is a
// generated, read-only mirror.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const from = resolve(process.argv[2] || resolve(here, '../../assets/js'));
const to = resolve(here, '../src/shared');
const FILES = ['utils.js', 'calc.js', 'email.js', 'seed.js'];
const HEADER = '// GENERATED by backend/scripts/sync-shared.mjs from assets/js — do not edit here.\n';

await mkdir(to, { recursive: true });
for (const f of FILES) {
  const src = resolve(from, f);
  await copyFile(src, resolve(to, f));
  const body = await readFile(resolve(to, f), 'utf8');
  if (!body.startsWith(HEADER)) await writeFile(resolve(to, f), HEADER + body);
}
console.log(`[shared] copied ${FILES.join(', ')} from ${from}`);
